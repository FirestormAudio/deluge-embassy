//! In-memory 128×48 OLED for the web simulator: one byte per pixel (0 or 255) so
//! JS can blit it straight to a canvas, plus the minimal 5×7 bitmap font lifted
//! from `deluge-bsp`'s OLED renderer (kept here so the wasm core depends only on
//! `deluge-wren-core` + `wren-sys`).

pub const WIDTH: usize = 128;
pub const HEIGHT: usize = 48;

pub struct Oled {
    /// Row-major, one byte per pixel: 0 = off, 255 = on.
    pub px: [u8; WIDTH * HEIGHT],
}

impl Oled {
    pub const fn new() -> Self {
        Oled { px: [0; WIDTH * HEIGHT] }
    }

    pub fn clear(&mut self) {
        self.px = [0; WIDTH * HEIGHT];
    }

    pub fn set_pixel(&mut self, x: usize, y: usize, on: bool) {
        if x < WIDTH && y < HEIGHT {
            self.px[y * WIDTH + x] = if on { 255 } else { 0 };
        }
    }

    /// Draw an ASCII string at pixel (`x`, `y`). Glyphs are 5 px wide + 1 px gap,
    /// clipped to display width.
    pub fn draw_str(&mut self, mut x: usize, y: usize, s: &[u8]) {
        for &ch in s {
            if x + 6 > WIDTH {
                break;
            }
            let cols = glyph(ch);
            for (col_idx, &col_bits) in cols.iter().enumerate() {
                for bit in 0..7u8 {
                    if col_bits & (1 << bit) != 0 {
                        self.set_pixel(x + col_idx, y + bit as usize, true);
                    }
                }
            }
            x += 6;
        }
    }
}

/// 5-column glyph for `ch` (printable ASCII, upper-cased). Each byte is one pixel
/// column; bit 0 = top, bit 6 = bottom. Mirrors `deluge_bsp::oled::text::glyph`.
fn glyph(ch: u8) -> [u8; 5] {
    match ch.to_ascii_uppercase() {
        b' ' => [0x00, 0x00, 0x00, 0x00, 0x00],
        b'!' => [0x00, 0x5F, 0x00, 0x00, 0x00],
        b'.' => [0x00, 0x60, 0x60, 0x00, 0x00],
        b'-' => [0x08, 0x08, 0x08, 0x08, 0x08],
        b'_' => [0x40, 0x40, 0x40, 0x40, 0x40],
        b'/' => [0x20, 0x10, 0x08, 0x04, 0x02],
        b':' => [0x00, 0x36, 0x36, 0x00, 0x00],
        b'0' => [0x3E, 0x51, 0x49, 0x45, 0x3E],
        b'1' => [0x00, 0x42, 0x7F, 0x40, 0x00],
        b'2' => [0x42, 0x61, 0x51, 0x49, 0x46],
        b'3' => [0x21, 0x41, 0x45, 0x4B, 0x31],
        b'4' => [0x18, 0x14, 0x12, 0x7F, 0x10],
        b'5' => [0x27, 0x45, 0x45, 0x45, 0x39],
        b'6' => [0x3C, 0x4A, 0x49, 0x49, 0x30],
        b'7' => [0x01, 0x71, 0x09, 0x05, 0x03],
        b'8' => [0x36, 0x49, 0x49, 0x49, 0x36],
        b'9' => [0x06, 0x49, 0x49, 0x29, 0x1E],
        b'A' => [0x7E, 0x11, 0x11, 0x11, 0x7E],
        b'B' => [0x7F, 0x49, 0x49, 0x49, 0x36],
        b'C' => [0x3E, 0x41, 0x41, 0x41, 0x22],
        b'D' => [0x7F, 0x41, 0x41, 0x22, 0x1C],
        b'E' => [0x7F, 0x49, 0x49, 0x49, 0x41],
        b'F' => [0x7F, 0x09, 0x09, 0x09, 0x01],
        b'G' => [0x3E, 0x41, 0x49, 0x49, 0x7A],
        b'H' => [0x7F, 0x08, 0x08, 0x08, 0x7F],
        b'I' => [0x00, 0x41, 0x7F, 0x41, 0x00],
        b'J' => [0x20, 0x40, 0x41, 0x3F, 0x01],
        b'K' => [0x7F, 0x08, 0x14, 0x22, 0x41],
        b'L' => [0x7F, 0x40, 0x40, 0x40, 0x40],
        b'M' => [0x7F, 0x02, 0x0C, 0x02, 0x7F],
        b'N' => [0x7F, 0x04, 0x08, 0x10, 0x7F],
        b'O' => [0x3E, 0x41, 0x41, 0x41, 0x3E],
        b'P' => [0x7F, 0x09, 0x09, 0x09, 0x06],
        b'Q' => [0x3E, 0x41, 0x51, 0x21, 0x5E],
        b'R' => [0x7F, 0x09, 0x19, 0x29, 0x46],
        b'S' => [0x46, 0x49, 0x49, 0x49, 0x31],
        b'T' => [0x01, 0x01, 0x7F, 0x01, 0x01],
        b'U' => [0x3F, 0x40, 0x40, 0x40, 0x3F],
        b'V' => [0x1F, 0x20, 0x40, 0x20, 0x1F],
        b'W' => [0x3F, 0x40, 0x38, 0x40, 0x3F],
        b'X' => [0x63, 0x14, 0x08, 0x14, 0x63],
        b'Y' => [0x07, 0x08, 0x70, 0x08, 0x07],
        b'Z' => [0x61, 0x51, 0x49, 0x45, 0x43],
        _ => [0x7F, 0x41, 0x41, 0x41, 0x7F], // solid box for unknown
    }
}
